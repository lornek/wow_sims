export function foreverSpellbook(className, catalog, trees, groups) {
  const trained = new Set(foreverTrainerSpells[className] ?? []);
  const active = new Set(foreverActiveTalents[className] ?? []);
  const nodes = new Map(trees.flatMap(tree => tree.nodes.map(node => [node.name, {node, tree}])));
  const result = {};
  for (const [name, entry] of Object.entries(catalog)) {
    if (groups[name]?.[1] === 'removed' || (nodes.has(name) ? !active.has(name) : !trained.has(name))) continue;
    result[name] = {...entry, talentAbility:nodes.has(name)};
  }
  for (const name of active) {
    if (result[name] || !nodes.has(name) || groups[name]?.[1] === 'removed') continue;
    const {node, tree} = nodes.get(name);
    result[name] = {icon:node.icon + '.jpg', talentAbility:true, school:tree.slug, ranks:[{rank:'', level:10 + (node.row - 1) * 5, details:tree.name + ' talent ability', description:node.description[0] ?? name}]};
  }
  return result;
}
